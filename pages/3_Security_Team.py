def severity_score(severity: str, incident_id: str) -> int:
    """Stable SOC triage score; this is not the model's attack probability."""
    ranges = {
        "Low": (10, 20),
        "Medium": (40, 60),
        "High": (70, 85),
        "Critical": (90, 100),
    }
    key = str(severity).strip().title()
    if key not in ranges:
        return 0
    low, high = ranges[key]
    digest = hashlib.sha256(str(incident_id).encode("utf-8")).hexdigest()
    return low + (int(digest[:8], 16) % (high - low + 1))


